const RISK: Record<RiskLevel, { label: string; text: string; rule: string }> = {
  low: { label: 'Low', text: 'text-emerald-300', rule: 'bg-emerald-400' },
  elevated: { label: 'Elevated', text: 'text-amber-200', rule: 'bg-amber-400' },
  high: { label: 'High', text: 'text-orange-300', rule: 'bg-orange-400' },
  severe: { label: 'Severe', text: 'text-red-300', rule: 'bg-red-500' },
};

const SEV_RULE: Record<string, string> = { critical: 'bg-red-500', high: 'bg-red-400', medium: 'bg-amber-400', low: 'bg-sky-400' };

function FleetTelemetry() {
  const { metrics, simulation } = useSentinel();
  const series = useMemo(() => {
    const byTick = new Map<bigint, { lat: number; err: number; rpm: number; n: number }>();
    for (const m of metrics) {
      if (m.source !== 'simulation_engine') continue;
      const t = byTick.get(m.tick) ?? { lat: 0, err: 0, rpm: 0, n: 0 };
      t.lat += m.latencyMs;
      t.err += m.errorRate;
      t.rpm += m.requestRpm;
      t.n++;
      byTick.set(m.tick, t);
    }
    return [...byTick.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1)).slice(-30).map(([, v]) => ({ lat: v.lat / v.n, err: (v.err / v.n) * 100, rpm: v.rpm }));
  }, [metrics]);
  return (
    <Panel title="Fleet telemetry" actions={<span className="text-xs text-violet-300">Synthetic</span>}>
      {series.length < 2 ? (
        <p className="text-sm text-slate-500">{simulation?.telemetryEnabled === false ? 'Built-in telemetry is paused in People & access.' : 'Waiting for the simulation engine…'}</p>
      ) : (
        <div className="grid grid-cols-3 gap-4">
          <Sparkline label="Average latency" values={series.map(s => s.lat)} color="#94bcfa" format={v => `${v.toFixed(0)} ms`} />
          <Sparkline label="Average error rate" values={series.map(s => s.err)} color="#f87171" format={v => `${v.toFixed(1)}%`} />
          <Sparkline label="Total requests" values={series.map(s => s.rpm)} color="#b4bac3" format={v => `${(v / 1000).toFixed(1)}k/min`} />
        </div>
      )}
      <p className="mt-3 text-xs text-slate-500">
        Generated by the built-in simulation engine in SpacetimeDB{simulation ? `, tick ${String(simulation.tickCount)}, every ${simulation.intervalMs / 1000} s` : ''}. Not production telemetry.
      </p>
    </Panel>
  );
}

function IncidentQueue() {
  const { incidents, effects, recoveries, assetById, incidentAssets, myHex } = useSentinel();
  const list = useMemo(() => {
    const open = incidents.filter(i => i.status !== 'resolved').sort((a, b) => (SEVERITY_RANK[b.severity] ?? 0) - (SEVERITY_RANK[a.severity] ?? 0) || (a.createdAt.microsSinceUnixEpoch < b.createdAt.microsSinceUnixEpoch ? 1 : -1));
    const closed = incidents.filter(i => i.status === 'resolved').sort((a, b) => (a.updatedAt.microsSinceUnixEpoch < b.updatedAt.microsSinceUnixEpoch ? 1 : -1));
    return [...open, ...closed].slice(0, 6);
  }, [incidents]);
  const impactedNow = (id: bigint) => incidentAssets.filter(ia => ia.incidentId === id && ia.impactStatus !== 'recovered').length;

  if (list.length === 0) {
    return (
      <Panel title="Incidents">
        <EmptyState title="No active incidents. Launch a synthetic scenario to test the environment." hint="When an incident opens, it appears here with the next step to take." />
      </Panel>
    );
  }
  return (
    <Panel title="Incidents, most urgent first" actions={<Link to="/incidents" className="text-[13px] text-slate-400 hover:text-slate-100">All incidents</Link>} bodyClass="p-0">
      <ul className="divide-y divide-ink-700">
        {list.map(i => {
          const step = nextStep(i, { effects, recoveries, assetById, myHex });
          const resolved = i.status === 'resolved';
          return (
            <li key={String(i.incidentId)} className={`relative px-5 py-4 ${resolved ? 'opacity-70' : ''}`}>
              <span className={`absolute top-4 bottom-4 left-0 w-1 rounded-r ${resolved ? 'bg-ink-600' : (SEV_RULE[i.severity] ?? 'bg-slate-500')}`} aria-hidden />
              <div className="min-w-0 space-y-1.5">
                <div className="flex flex-wrap items-center gap-2">
                  <span className="ident">INC-{String(i.incidentId)}</span>
                  <SeverityBadge severity={i.severity} />
                  {i.isSimulation ? <SimBadge /> : <RealBadge />}
                </div>
                <Link to={`/incidents/${i.incidentId}`} className="block truncate text-[15px] font-semibold text-slate-50 hover:underline">
                  {i.title}
                </Link>
                <div className="text-[13px] text-slate-400">
                  {scenarioLabel(i.scenarioType)}, started at {assetById.get(i.initialAssetId)?.name ?? i.initialAssetId}. {impactedNow(i.incidentId)} services impacted now. Updated {relTime(i.updatedAt)}.
                </div>
                <div className="max-w-xl pt-2 pb-1">
                  <LifecycleRail status={i.status} />
                </div>
                {!resolved && (
                  <div className={`flex flex-wrap items-center gap-3 pt-1 text-sm ${step.waiting ? 'text-slate-400' : 'text-slate-100'}`}>
                    {step.waiting ? <Clock className="size-4 shrink-0 text-slate-500" aria-hidden /> : <ArrowRight className="size-4 shrink-0 text-amber-300" aria-hidden />}
                    <span className="min-w-0 flex-1">{step.text}</span>
                    {!step.waiting && (
                      <Link to={step.to} className="btn-primary py-1">
                        {step.cta}
                      </Link>
                    )}
                  </div>
                )}
              </div>
            </li>
          );
        })}
      </ul>
    </Panel>
  );
}

function ServiceMap() {
  const { assets } = useSentinel();
  const byEnv = useMemo(() => {
    const m = new Map<string, (typeof assets)[number][]>();
    for (const a of assets) m.set(a.environment, [...(m.get(a.environment) ?? []), a]);
    return [...m.entries()].sort();
  }, [assets]);
  return (
    <Panel title="Services by environment" actions={<Link to="/twin" className="text-[13px] text-slate-400 hover:text-slate-100">Open digital twin</Link>}>
      <div className="space-y-3">
        {byEnv.map(([env, list]) => (
          <div key={env}>
            <div className="mb-1.5 text-[13px] text-slate-400">{env}</div>
            <div className="flex flex-wrap gap-1.5">
              {list.map(a => {
                const exposed = a.impactType === 'exposed' && a.healthStatus === 'healthy';
                const color = exposed ? '#a78bfa' : (HEALTH_META[a.healthStatus]?.hex ?? '#5a606b');
                return (
                  <Link
                    key={a.assetId}
                    to="/twin"
                    title={`${a.name}: ${a.healthStatus}${exposed ? ' (at risk)' : ''}`}
                    className="inline-flex items-center gap-1.5 rounded-md border border-ink-700 bg-ink-850 px-2 py-1 text-xs text-slate-300 hover:border-ink-600 hover:text-slate-100"
                  >
                    <span className="size-2 rounded-full" style={{ background: a.healthStatus === 'healthy' && !exposed ? '#3d8a63' : color }} aria-hidden />
                    {a.name}
                  </Link>
                );
              })}
            </div>
          </div>
        ))}
      </div>
    </Panel>
  );
}

function Overview() {
  const { assets, incidents, events, assetById } = useSentinel();
  const counts = useMemo(() => healthCounts(assets), [assets]);
  const score = useMemo(() => healthScore(assets), [assets]);
  const risk = useMemo(() => riskSummary(incidents, assets), [incidents, assets]);
  const active = incidents.filter(i => i.status !== 'resolved');
  const recent = useMemo(() => chronological(events).slice(-14).reverse(), [events]);

  if (assets.length === 0) {
    return (
      <Panel>
        <EmptyState title="No virtual infrastructure is loaded. Initialize the demo environment." hint="An Incident Commander can initialize it from People & access. New connections also seed it automatically." />
      </Panel>
    );
  }
  const scoreTone = score >= 90 ? 'text-emerald-300' : score >= 60 ? 'text-amber-200' : 'text-red-300';
  const r = RISK[risk.level];

  return (
    <div className="space-y-5">
      <PageHeader title="Operations overview" purpose="What is happening right now, and what to do next." actions={<SimulationLauncher />} />

      <DatacenterHero />

      <section className="panel overflow-hidden" role="status" aria-label="System risk summary">
        <div className="flex flex-wrap items-stretch">
          <div className="relative flex min-w-56 flex-col justify-center gap-0.5 py-4 pr-8 pl-6">
            <span className={`absolute top-0 bottom-0 left-0 w-1.5 ${r.rule}`} aria-hidden />
            <span className="text-[13px] text-slate-400">Current system risk</span>
            <span className={`text-[2.4rem] leading-none font-semibold tracking-[-0.02em] ${r.text}`}>{r.label}</span>
          </div>
          <ul className="flex min-w-64 flex-1 flex-col justify-center gap-1 border-ink-700 px-6 py-4 text-sm text-slate-300 sm:border-l">
            {risk.reasons.map(x => (
              <li key={x}>{x}</li>
            ))}
          </ul>
          <div className="flex flex-col justify-center border-ink-700 px-6 py-4 sm:border-l">
            <span className="text-[13px] text-slate-400">Weighted availability</span>
            <span className={`text-[1.65rem] leading-tight font-semibold tabular-nums ${scoreTone}`}>{score}%</span>
          </div>
        </div>
        <div className="grid grid-cols-2 divide-ink-700 border-t border-ink-700 sm:grid-cols-4 sm:divide-x xl:grid-cols-8">
          <MetricCard label="Monitored services" value={counts.total} />
          <MetricCard label="Healthy" value={counts.healthy} tone="text-emerald-300" />
          <MetricCard label="Degraded" value={counts.degraded} tone={counts.degraded ? 'text-amber-200' : 'text-slate-500'} />
          <MetricCard label="Critical" value={counts.critical} tone={counts.critical ? 'text-red-300' : 'text-slate-500'} hint="Root causes" />
          <MetricCard label="Offline" value={counts.offline} tone={counts.offline ? 'text-slate-200' : 'text-slate-500'} hint="Via a dependency" />
          <MetricCard label="Recovering" value={counts.recovering} tone={counts.recovering ? 'text-sky-300' : 'text-slate-500'} />
          <MetricCard label="At risk" value={counts.atRisk} tone={counts.atRisk ? 'text-violet-300' : 'text-slate-500'} hint="Potentially exposed" />
          <MetricCard label="Active incidents" value={active.length} tone={active.length ? 'text-red-300' : 'text-slate-500'} />
        </div>
      </section>

      <div className="grid gap-5 xl:grid-cols-[minmax(0,1.7fr)_minmax(0,1fr)]">
        <IncidentQueue />
        <Panel title="Live activity" bodyClass="max-h-[34rem] overflow-y-auto px-4 py-3">
          {recent.length ? <Timeline events={recent} assetById={assetById} showIncident compact /> : <EmptyState title="Nothing has happened yet." />}
        </Panel>
      </div>

      <SensorPanel />

      <div className="grid gap-5 xl:grid-cols-2">
        <ServiceMap />
        <FleetTelemetry />
      </div>
    </div>
  );
}

export function OverviewPage() {
  return (
    <PageGate>
      <Overview />
    </PageGate>
  );
}
